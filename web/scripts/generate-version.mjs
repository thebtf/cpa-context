// The client shows the plugin's version in its own UI, and the plugin reports
// the same number to the host. Two sources drift: the constant in plugin.go is
// bumped on every release, and a literal here would keep saying whatever it was
// copied with.
//
// This reads plugin.go at build time and writes src/client/generated.ts, so the
// number the page shows is the number the binary declares.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const pluginGo = join(here, '..', '..', 'plugin.go')
const source = readFileSync(pluginGo, 'utf8')

const match = source.match(/pluginVersion\s*=\s*"([^"]+)"/)
if (match === null) {
  throw new Error('pluginVersion is not declared in plugin.go')
}
const version = match[1]

const nameMatch = source.match(/pluginID\s*=\s*"([^"]+)"/)
const name = nameMatch === null ? 'cpa-context' : nameMatch[1]

const repoMatch = source.match(/pluginRepo\s*=\s*"([^"]+)"/)
const repo = repoMatch === null ? '' : repoMatch[1]

const out = join(here, '..', 'src', 'client', 'generated.ts')
writeFileSync(out, [
  '// Generated by scripts/generate-version.mjs from plugin.go. Do not edit.',
  `export const PLUGIN_NAME = ${JSON.stringify(name)}`,
  `export const PLUGIN_VERSION = ${JSON.stringify(version)}`,
  `export const PLUGIN_REPO = ${JSON.stringify(repo)}`,
  '',
].join('\n'), 'utf8')

console.log(`generated ${out}: ${name} ${version}`)
